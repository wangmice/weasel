# setup-build-env.ps1 - weasel 构建环境一键准备（可重复执行，已就绪的步骤会自动跳过）
#
# 复现内容：
#   1. scoop 安装工具依赖: aria2 / 7zip / xmake / pwsh
#   2. 使用与 CI 相同的默认 Boost 源码版本（可由 boost_version/BOOST_ROOT 覆盖）
#   3. get-rime.ps1 -use dev 下载 librime 开发文件 (rime_*.h, rime.lib x86+x64, rime.dll, opencc 数据)
#   4. 通过 build.bat 校验/重建 B2，并编译 /MT 静态库到 <boost>\stage\lib (x64 + x86)
#   5. 生成 env.bat (BOOST_ROOT + VS2022/v143 toolset)
#   6. 补齐 afxres.h stub 与 PerMonitorHighDPIAware.manifest
#
# 用法:
#   powershell/pwsh -ExecutionPolicy Bypass -File .\setup-build-env.ps1           # 仅准备环境
#   powershell/pwsh -ExecutionPolicy Bypass -File .\setup-build-env.ps1 -Build    # 准备后顺便 xmake 编译 x64+x86
#
# 依赖: scoop、Visual Studio 2022 含 ATL 组件（MFC 可选）
param(
  [switch]$Build
)
$ErrorActionPreference = 'Stop'
$repo = $PSScriptRoot
if (-not $repo) { $repo = Split-Path -Parent $MyInvocation.MyCommand.Path }

. (Join-Path $repo 'BuildEnvPolicy.ps1')

function Step($msg) { Write-Host "`n=== $msg ===" -ForegroundColor Cyan }

function Resolve-Vs2022Installation {
  if ($env:VSINSTALLDIR -and $env:VisualStudioVersion -match '^17\.' -and
      (Test-Path (Join-Path $env:VSINSTALLDIR 'VC\Auxiliary\Build\vcvars64.bat'))) {
    return $env:VSINSTALLDIR.TrimEnd('\')
  }

  $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
  if (-not (Test-Path $vswhere)) { throw 'vswhere not found; is Visual Studio 2022 installed?' }
  $candidates = @(& $vswhere -version '[17.0,18.0)' -products '*' -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath)
  $vsDir = $candidates | Where-Object { $_ -and (Test-Path (Join-Path $_ 'VC\Auxiliary\Build\vcvars64.bat')) } | Select-Object -First 1
  if (-not $vsDir) { throw 'Visual Studio 2022 with the C++ toolchain was not found' }
  return $vsDir.Trim()
}

# --------------------------------------------------------------------------
Step "0/6 检查 scoop 及工具依赖 (aria2 7zip xmake pwsh)"
if (-not (Get-Command scoop -ErrorAction SilentlyContinue)) {
  throw "scoop not found; install scoop first: https://scoop.sh"
}
foreach ($app in @('aria2', '7zip', 'xmake', 'pwsh')) {
  $installed = [bool](scoop prefix $app 2>$null)
  if ($installed) {
    Write-Host "  [ok] $app"
  } else {
    Write-Host "  [install] $app (via scoop) ..."
    scoop install $app
    if ($LASTEXITCODE -ne 0) { throw "scoop install $app failed" }
  }
}

# --------------------------------------------------------------------------
Step "1/6 定位/准备 Boost 与 Visual Studio 2022"
$boostVersion = if ($env:boost_version) { $env:boost_version.Trim() } else { Get-WeaselDefaultBoostVersion }
$boostToken = $boostVersion.Replace('.', '_')
$explicitBoostRoot = -not [string]::IsNullOrWhiteSpace($env:BOOST_ROOT)
$boostRoot = if ($explicitBoostRoot) {
  $env:BOOST_ROOT.Trim().Trim('"')
} else {
  Join-Path $repo "deps\boost_$boostToken"
}

$sourceProblems = @(Get-WeaselBoostSourceProblems -BoostRoot $boostRoot)
if ($sourceProblems.Count -ne 0) {
  if ($explicitBoostRoot) {
    throw "explicit BOOST_ROOT is incomplete ($boostRoot): $($sourceProblems -join ', ')"
  }

  $depsDir = Join-Path $repo 'deps'
  New-Item -ItemType Directory -Path $depsDir -Force | Out-Null
  $archive = "boost_$boostToken.7z"
  $url = "https://archives.boost.io/release/$boostVersion/source/$archive"
  Write-Host "  [download] Boost $boostVersion from $url"
  & aria2c -c $url -d $depsDir
  if ($LASTEXITCODE -ne 0) { throw "Boost $boostVersion download failed" }

  Push-Location $depsDir
  try {
    & 7z x $archive -y
    if ($LASTEXITCODE -ne 0) { throw "Boost $boostVersion extraction failed" }
  } finally { Pop-Location }

  $sourceProblems = @(Get-WeaselBoostSourceProblems -BoostRoot $boostRoot)
  if ($sourceProblems.Count -ne 0) {
    throw "Boost source is incomplete after extraction ($boostRoot): $($sourceProblems -join ', ')"
  }
}

$vsDir = Resolve-Vs2022Installation
Write-Host "  Boost       = $boostVersion"
Write-Host "  BOOST_ROOT  = $boostRoot"
Write-Host "  VS2022      = $vsDir"

# --------------------------------------------------------------------------
Step "2/6 生成 env.bat"
Set-Content -Path (Join-Path $repo 'env.bat') -Encoding ASCII -Value @(
  'rem Generated by setup-build-env.ps1'
  "set `"BOOST_ROOT=$boostRoot`""
  'set "BJAM_TOOLSET=msvc-14.3"'
  'set "CMAKE_GENERATOR=Visual Studio 17 2022"'
  'set "PLATFORM_TOOLSET=v143"'
  'set "XMAKE_VS=2022"'
  'set "XMAKE_VS_TOOLSET=14.3"'
)
Write-Host "  env.bat written for VS2022/v143"

# --------------------------------------------------------------------------
Step "3/6 生成 include/afxres.h stub (仅在 VS 未安装 MFC 组件时需要)"
$afxres = Join-Path $repo 'include\afxres.h'
if (Test-Path $afxres) {
  Write-Host "  [skip] already exists"
} else {
  Set-Content -Path $afxres -Encoding ASCII -Value @(
    '// Minimal stand-in for the MFC afxres.h, which is only pulled in by the'
    '// AppStudio TEXTINCLUDE 2 boilerplate in the .rc files. The resources here'
    '// use nothing from MFC itself; the standard Win32 resource definitions from'
    '// the Windows SDK are all that is needed.'
    '#ifndef _AFXRES_H'
    '#define _AFXRES_H'
    '#include "winres.h"'
    '#endif'
  )
  Write-Host "  [created] include/afxres.h"
}

# --------------------------------------------------------------------------
Step "4/6 复制 PerMonitorHighDPIAware.manifest 到仓库根"
$manifest = Join-Path $repo 'PerMonitorHighDPIAware.manifest'
if (Test-Path $manifest) {
  Write-Host "  [skip] already exists"
} else {
  $candidates = @(
    Get-Item "$vsDir\VC\Tools\MSVC\*\include\Manifest\PerMonitorHighDPIAware.manifest" -ErrorAction SilentlyContinue
    Get-Item "$vsDir\VC\Tools\MSVC\*\atlmfc\include\Manifest\PerMonitorHighDPIAware.manifest" -ErrorAction SilentlyContinue
  )
  if (-not $candidates) {
    $candidates = Get-ChildItem $vsDir -Recurse -Filter 'PerMonitorHighDPIAware.manifest' -ErrorAction SilentlyContinue | Select-Object -First 1
  }
  if (-not $candidates) { throw "PerMonitorHighDPIAware.manifest not found under $vsDir" }
  Copy-Item $candidates[0].FullName $manifest
  Write-Host "  [copied] $($candidates[0].FullName)"
}

# --------------------------------------------------------------------------
Step "5/6 获取 librime 开发文件 (get-rime.ps1 -use dev)"
$needRime = -not (
  (Test-Path (Join-Path $repo 'include\rime_api.h')) -and
  (Test-Path (Join-Path $repo 'lib64\rime.lib')) -and
  (Test-Path (Join-Path $repo 'lib\rime.lib')) -and
  (Test-Path (Join-Path $repo 'output\rime.dll')) -and
  (Test-Path (Join-Path $repo 'output\Win32\rime.dll')))
if ($needRime) {
  Push-Location $repo
  try {
    pwsh -NoProfile -ExecutionPolicy Bypass -File .\get-rime.ps1 -use dev
    if ($LASTEXITCODE -ne 0) { throw "get-rime.ps1 failed" }
  } finally { Pop-Location }
} else {
  Write-Host "  [skip] rime files already present"
}

# --------------------------------------------------------------------------
Step "6/6 编译 Boost /MT 静态库到 stage\lib (x64 + x86)"
$stageLibDir = Join-Path $boostRoot 'stage\lib'
$missingBoost = @(Get-WeaselMissingBoostPatterns -StageLibDir $stageLibDir)
if ($missingBoost.Count -eq 0) {
  Write-Host "  [skip] required x64+x86 Boost static libraries already present"
} else {
  Write-Host "  missing Boost libraries:"
  $missingBoost | ForEach-Object { Write-Host "    $_" }
  $vcvars = Join-Path $vsDir 'VC\Auxiliary\Build\vcvars64.bat'
  if (-not (Test-Path $vcvars)) { throw "vcvars64.bat not found under $vsDir" }
  $cmd = @"
@echo off
call "$vcvars" || exit /b 1
cd /d "$repo"
call build.bat boost || exit /b 1
"@
  $tmpCmd = Join-Path $env:TEMP 'weasel-boost-stage.cmd'
  Set-Content -Path $tmpCmd -Encoding ASCII -Value $cmd
  Write-Host "  building Boost static libs with VS2022/v143 ..."
  cmd /c $tmpCmd
  $ok = ($LASTEXITCODE -eq 0)
  Remove-Item $tmpCmd -ErrorAction SilentlyContinue
  if (-not $ok) { throw "boost stage build failed" }

  $missingBoost = @(Get-WeaselMissingBoostPatterns -StageLibDir $stageLibDir)
  if ($missingBoost.Count -ne 0) {
    throw "Boost stage is still incomplete: $($missingBoost -join ', ')"
  }
  Write-Host "  [done] required x64+x86 Boost static libraries are present"
}

# --------------------------------------------------------------------------
if ($Build) {
  Step "构建 weasel (x64 + x86, 固定 Visual Studio 2022/v143)"
  Push-Location $repo
  try {
    xmake f -a x64 -m release --vs=2022 --vs_toolset=14.3 -y
    if ($LASTEXITCODE -ne 0) { throw "xmake config x64 failed" }
    xmake -y
    if ($LASTEXITCODE -ne 0) { throw "xmake build x64 failed" }
    xmake f -a x86 -m release --vs=2022 --vs_toolset=14.3 -y
    if ($LASTEXITCODE -ne 0) { throw "xmake config x86 failed" }
    xmake -y
    if ($LASTEXITCODE -ne 0) { throw "xmake build x86 failed" }
  } finally { Pop-Location }
}

Write-Host "`n=== 环境就绪 ===" -ForegroundColor Green
Write-Host '  xmake:             xmake f -a x64 -m release --vs=2022 --vs_toolset=14.3 -y ; xmake   (x86 同理换 -a x86)'
Write-Host '  传统方式:          在 VS2022 Developer Command Prompt 中运行 build.bat'
Write-Host "  Boost:             默认 $boostVersion；可用 boost_version / BOOST_ROOT 显式覆盖"
